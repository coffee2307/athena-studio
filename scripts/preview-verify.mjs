import {readFileSync} from "node:fs";
import {strict as assert} from "node:assert";
const base=process.argv[2]||"http://127.0.0.1:3184";
const password=readFileSync(new URL("../.qa/preview-password.txt",import.meta.url),"utf8").trim();
const authorization="Basic "+Buffer.from("athena:"+password).toString("base64");
const noAuth=await fetch(base+"/",{redirect:"manual"});
assert.equal(noAuth.status,401,"A visitor without a password must be blocked");
const authHeaders={Authorization:authorization};
const htmlResponse=await fetch(base+"/",{headers:authHeaders});
assert.equal(htmlResponse.status,200);
assert.match(htmlResponse.headers.get("cache-control")||"",/no-store/);
assert.match(htmlResponse.headers.get("x-robots-tag")||"",/noindex/);
const html=await htmlResponse.text();
const css=html.match(/href="([^"]+\.css(?:\?[^"]*)?)"/);
assert.ok(css,"A compiled stylesheet URL is required");
const cssResponse=await fetch(new URL(css[1],base),{headers:authHeaders});
assert.equal(cssResponse.status,200,"Compiled CSS must be accessible");
assert.match(cssResponse.headers.get("cache-control")||"",/immutable/);
assert.match(cssResponse.headers.get("cache-control")||"",/private/);
const apiResponse=await fetch(base+"/api/identity/get-session",{headers:authHeaders});
assert.equal(apiResponse.status,404,"Auth API must be blocked on public preview");
const postResponse=await fetch(base+"/contact",{method:"POST",headers:authHeaders});
assert.equal(postResponse.status,405,"State-changing POST must be blocked");
console.log("PRIVATE_PREVIEW_QA_PASS",{host:new URL(base).hostname,unauthorized:noAuth.status,html:htmlResponse.status,css:cssResponse.status,cssCache:cssResponse.headers.get("cache-control"),api:apiResponse.status,post:postResponse.status});
