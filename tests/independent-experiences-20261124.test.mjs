import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(p,"utf8");
test("FORMA and Poppy have independent multi-page grammars, not the legacy artifact template",()=>{
 const arch=read("templates/architecture-studio/src/components/Site.tsx");
 const atlas=read("templates/architecture-studio/src/components/FormaAtlas.tsx");
 const pet=read("templates/pet-store/src/components/Site.tsx");
 const market=read("templates/pet-store/src/components/PoppyMarket.tsx");
 assert.match(arch,/ArchitectureExperience/);
 assert.match(arch,/FormaAtlas/);
 assert.match(atlas,/materialControl/);
 assert.match(atlas,/setMaterial\(i\)/);
 assert.match(atlas,/setFilter\(x\)/);
 assert.match(atlas,/setReview\(true\)/);
 assert.match(pet,/PoppyMarket/);
 assert.match(market,/setCart/);
 assert.match(market,/Giỏ hàng mô phỏng/);
 assert.match(market,/setFilter\(x\)/);
 assert.match(market,/setDrawer\(true\)/);
 assert.doesNotMatch(arch,/VISUAL STUDY \/ DEMONSTRATION MATERIAL|START A CONVERSATION/);
 assert.doesNotMatch(pet,/VISUAL STUDY \/ DEMONSTRATION MATERIAL|START A CONVERSATION/);
 const atlasCSS=read("templates/architecture-studio/src/components/FormaAtlas.module.css");
 const marketCSS=read("templates/pet-store/src/components/PoppyMarket.module.css");
 assert.match(atlasCSS,/\.labStage/);
 assert.match(marketCSS,/\.shelf/);
 assert.match(atlasCSS,/prefers-reduced-motion/);
 assert.match(marketCSS,/prefers-reduced-motion/);
});
test("Athena template collection is editorial and responsive rather than cloned card rows",()=>{
 const gallery=read("components/templates/TemplateGallery.tsx");
 const css=read("app/template-editorial-gallery.css");
 assert.match(gallery,/data-presentation=\{index%5===0/);
 assert.match(gallery,/data-template=\{item\.slug\}/);
 assert.match(css,/grid-template-columns:repeat\(12/);
 assert.match(css,/grid-column:span 8/);
 assert.match(css,/data-template="fashion-archive"/);
 assert.match(css,/data-template="pet-store"/);
 assert.match(css,/@media\(max-width:760px\)/);
 assert.doesNotMatch(gallery,/String\(index\+1\)\.padStart\(2,"0"\)/);
});
